"""Regenerate constraints.txt: the exact dependency versions releases are tested with.

pyproject.toml keeps Duo's supported dependency ranges; constraints.txt pins
one tested resolution. For each given Python interpreter, Duo is installed into
a clean virtual environment and the resolved versions are recorded. Packages
whose resolution differs between interpreters get environment markers.

  python scripts/update_constraints.py /path/to/python3.10 ... /path/to/python3.14

Then run the test suite against the new pins (CI does so on every push) and
review `pip-audit -r constraints.txt` before releasing.
"""
from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "constraints.txt"


def resolve(python: str, scratch: Path) -> tuple[str, dict[str, str]]:
    version = subprocess.run([python, "-c", "import sys; print('%d.%d' % sys.version_info[:2])"],
                             capture_output=True, text=True, check=True).stdout.strip()
    env = scratch / f"venv-{version}"
    subprocess.run([python, "-m", "venv", str(env)], check=True)
    pip = [str(env / "bin" / "python"), "-m", "pip", "--disable-pip-version-check", "-q"]
    subprocess.run([*pip, "install", "--no-cache-dir", str(ROOT)], check=True)
    frozen = subprocess.run([*pip, "freeze", "--exclude", "duo-plan"],
                            capture_output=True, text=True, check=True).stdout
    pins = dict(line.split("==", 1) for line in frozen.splitlines() if "==" in line)
    return version, pins


def main(pythons: list[str]) -> None:
    if not pythons:
        raise SystemExit(__doc__)
    with tempfile.TemporaryDirectory() as scratch:
        resolutions = dict(resolve(python, Path(scratch)) for python in pythons)
    versions = sorted(resolutions, key=lambda v: tuple(map(int, v.split("."))))
    names = sorted({name for pins in resolutions.values() for name in pins}, key=str.lower)
    lines = [f"# Tested dependency versions for Python {', '.join(versions)}.",
             "# Generated by scripts/update_constraints.py; do not edit by hand.",
             "# Install with: pip install duo-plan -c constraints.txt"]
    for name in names:
        found = {v: resolutions[v].get(name) for v in versions}
        if len(set(found.values())) == 1:
            lines.append(f"{name}=={found[versions[0]]}")
        else:
            for v, pinned in found.items():
                if pinned:
                    lines.append(f'{name}=={pinned} ; python_version == "{v}"')
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(names)} packages, Python {', '.join(versions)})")


if __name__ == "__main__":
    main(sys.argv[1:])
